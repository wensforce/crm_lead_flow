export const INDIAN_CITIES = [
  ...new Set([...METRO_CITIES, ...OTHER_CITIES]),
].sort((a, b) => a.localeCompare(b));

export const filterIndianCities = (query) => {
  const normalized = String(query || "").trim().toLowerCase();
  if (!normalized) return METRO_CITIES;

  return INDIAN_CITIES.filter((city) => {
    if (city.toLowerCase().includes(normalized)) return true;
    return (CITY_ALIASES[city] || []).some((alias) =>
      alias.toLowerCase().includes(normalized),
    );
  });
};
